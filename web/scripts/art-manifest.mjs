// Writes web/src/content/art.ts, the typed art manifest.
//
// Inputs
//   assets-src/art-manifest.json      written by optimize-art.mjs (one entry per generated piece)
//   web/public/previews/*.webp        scanned here, so a partial capture run still yields a full list
//
// Outputs, all derived from the files above: ART, PREVIEWS and PREVIEW_LQIP (the tiny blurred
// placeholder of every preview, regenerated each run so a recaptured preview can never keep the old
// page's placeholder).
//
// Both optimize-art.mjs and capture-previews.mjs call writeArtManifest(), so the file is always
// consistent with what is on disk. Never edit art.ts by hand.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const repoRoot = resolve(here, '..', '..');
export const webRoot = join(repoRoot, 'web');
export const manifestJson = join(repoRoot, 'assets-src', 'art-manifest.json');
export const previewsDir = join(webRoot, 'public', 'previews');
export const artTs = join(webRoot, 'src', 'content', 'art.ts');

/** Catalog gateway ids (shared/catalog.ts) mapped to the art piece that represents them. */
const GATEWAY_ART = {
  cloud: 'gateway-cloud',
  edge: 'gateway-edge',
  ai: 'gateway-ai',
  games: 'gateway-games',
  docs: 'gateway-docs',
  explorer: 'gateway-explorer',
  'run-a-node': 'gateway-node',
  flux: 'gateway-site',
  zelcore: 'gateway-wallet',
  ssp: 'gateway-wallet',
};

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** Biome's line width for web/, so the generated file passes `biome check` untouched. */
const LINE_WIDTH = 110;

/** A 16x10 WebP (about 80 bytes) as a data URL, shown soft under a preview while the real one loads. */
function lqipFor(file) {
  const webp = execFileSync(
    'magick',
    [file, '-resize', '16x10!', '-quality', '35', '-define', 'webp:method=6', 'webp:-'],
    { maxBuffer: 1024 * 1024 },
  );
  return `data:image/webp;base64,${webp.toString('base64')}`;
}

function readArt() {
  if (!existsSync(manifestJson)) return [];
  return JSON.parse(readFileSync(manifestJson, 'utf8')).art ?? [];
}

function readPreviews() {
  if (!existsSync(previewsDir)) return [];
  const out = [];
  for (const f of readdirSync(previewsDir)
    .filter((n) => n.endsWith('.webp'))
    .sort()) {
    const id = f.replace(/\.webp$/, '');
    const [w, h] = execFileSync('magick', ['identify', '-format', '%w %h', join(previewsDir, f)], {
      encoding: 'utf8',
    })
      .trim()
      .split(' ')
      .map(Number);
    out.push({ id, src: `/previews/${f}`, width: w, height: h, lqip: lqipFor(join(previewsDir, f)) });
  }
  return out;
}

export function writeArtManifest() {
  const art = readArt();
  const previews = readPreviews();
  const ids = art.map((a) => a.id);

  const lines = [];
  lines.push(
    '/**',
    ' * Art manifest: generated artwork and captured app previews.',
    ' *',
    ' * GENERATED by web/scripts/optimize-art.mjs (ART) and web/scripts/capture-previews.mjs (PREVIEWS).',
    ' * Do not edit by hand. Prompts and originals: assets-src/. Provenance: web/public/art/README.md.',
    ' *',
    " * Using the art: place it on black and let it blend. `blend: 'screen'` pieces are emissive light on",
    ' * pure black, so `mix-blend-mode: screen` (or additive blending in WebGL) removes the box. Prefer',
    ' * `<picture>` with the `avif` source first and `src` (WebP) as the fallback.',
    ' */',
    '',
    "export type ArtBlend = 'screen' | 'normal';",
    '',
    'export interface ArtAsset {',
    '  /** Public URL of the WebP. Always present. */',
    '  src: string;',
    '  /** Public URL of the AVIF, present only where it is meaningfully smaller than the WebP. */',
    '  avif?: string;',
    '  width: number;',
    '  height: number;',
    '  /** Average colour as #rrggbb, for placeholders and the blur-up background. */',
    '  avg: string;',
    '  /**',
    '   * Where the visible content sits, as [left, top, right, bottom] fractions of the frame (everything',
    '   * above 12 percent luminance). Anything outside is black margin: safe to crop, safe to parallax into.',
    '   */',
    '  box: readonly [number, number, number, number];',
    '  /** True when the file carries a real alpha channel (the sprites). */',
    '  alpha?: boolean;',
    '  /** Short, specific description. Use as `alt` where the art carries meaning, else alt="". */',
    '  alt: string;',
    "  /** 'screen' for emissive art on pure black, 'normal' for opaque or alpha pieces. */",
    '  blend: ArtBlend;',
    '}',
    '',
    'export type ArtId =',
  );
  for (const id of ids) lines.push(`  | ${q(id)}`);
  lines[lines.length - 1] += ';';
  lines.push('', 'export const ART: Record<ArtId, ArtAsset> = {');
  for (const a of art) {
    lines.push(`  ${q(a.id)}: {`);
    lines.push(`    src: ${q(a.src)},`);
    if (a.avif) lines.push(`    avif: ${q(a.avif)},`);
    lines.push(`    width: ${a.width},`);
    lines.push(`    height: ${a.height},`);
    lines.push(`    avg: ${q(a.avg)},`);
    lines.push(`    box: [${(a.box ?? [0, 0, 1, 1]).join(', ')}],`);
    if (a.alpha) lines.push('    alpha: true,');
    lines.push(`    alt: ${q(a.alt)},`);
    lines.push(`    blend: ${q(a.blend)},`);
    lines.push('  },');
  }
  lines.push('};', '');

  lines.push(
    '/** Catalog gateway id (`GATEWAYS` in shared/catalog.ts) to its art piece. The two wallets share one. */',
    'export const GATEWAY_ART: Record<string, ArtId> = {',
  );
  for (const [k, v] of Object.entries(GATEWAY_ART)) {
    if (ids.includes(v)) lines.push(`  ${/^[a-z]+$/.test(k) ? k : q(k)}: ${q(v)},`);
  }
  lines.push('};', '');

  lines.push(
    '/** Tier name to its art piece. The dominant colour of each is the tier colour. */',
    'export const TIER_ART: Record<string, ArtId> = {',
  );
  for (const t of ['cumulus', 'nimbus', 'stratus']) {
    if (ids.includes(`tier-${t}`)) lines.push(`  ${t}: ${q(`tier-${t}`)},`);
  }
  lines.push('};', '');

  lines.push(
    '/**',
    ' * Captured app and host previews (960x600 WebP), keyed by catalog id (`COMMUNITY_APPS` and',
    ' * `NODE_HOSTS`). An id is absent when its capture failed: fall back to generated art.',
    ' */',
    'export const PREVIEWS: Record<string, { src: string; width: number; height: number }> = {',
  );
  for (const p of previews) {
    lines.push(`  ${/^[a-z]+$/.test(p.id) ? p.id : q(p.id)}: {`);
    lines.push(`    src: ${q(p.src)},`);
    lines.push(`    width: ${p.width},`);
    lines.push(`    height: ${p.height},`);
    lines.push('  },');
  }
  lines.push('};', '');

  lines.push(
    '/**',
    ' * 16x10 WebP data URLs of every preview (about 80 bytes each), shown soft under the real image while it',
    " * loads. Generated from the same files as PREVIEWS, so a recaptured preview never keeps the old page's",
    ' * placeholder.',
    ' */',
    'export const PREVIEW_LQIP: Record<string, string> = {',
  );
  for (const p of previews) {
    const key = /^[a-z]+$/.test(p.id) ? p.id : q(p.id);
    const oneLine = `  ${key}: ${q(p.lqip)},`;
    // Biome moves a value that does not fit onto its own line; match it so the file needs no reformat.
    if (oneLine.length <= LINE_WIDTH) lines.push(oneLine);
    else lines.push(`  ${key}:`, `    ${q(p.lqip)},`);
  }
  lines.push('};', '');

  writeFileSync(artTs, lines.join('\n'));
  return { art: art.length, previews: previews.length, placeholders: previews.length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const r = writeArtManifest();
  console.log(`wrote ${artTs} (${r.art} art, ${r.previews} previews, ${r.placeholders} placeholders)`);
}
